def apply(path, flat_keys, sections):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    # flat keys (dashboard.*, payroll.*)
    for key, translations in flat_keys.items():
        section, leaf = key.split(".", 1)
        data.setdefault(section, {})[leaf] = translations[path.split("/")[-1][:2]]
    # whole sections
    for section_name, translations in sections.items():
        data[section_name] = translations[path.split("/")[-1][:2]]
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    return len(data)

